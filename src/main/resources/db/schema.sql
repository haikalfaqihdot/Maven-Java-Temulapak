-- TemuLapak - skema PostgreSQL (9 tabel sesuai ERD)
-- Dijalankan otomatis saat aplikasi start. Aman dijalankan berulang (IF NOT EXISTS).

CREATE TABLE IF NOT EXISTS pemilik_tempat (
    id_pemilik  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama        VARCHAR(100) NOT NULL,
    email       VARCHAR(150) NOT NULL UNIQUE,
    no_telepon  VARCHAR(20),
    password    VARCHAR(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS penyewa (
    id_penyewa  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama        VARCHAR(100) NOT NULL,
    email       VARCHAR(150) NOT NULL UNIQUE,
    no_telepon  VARCHAR(20),
    password    VARCHAR(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS admin (
    id_admin    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama        VARCHAR(100) NOT NULL,
    email       VARCHAR(150) NOT NULL UNIQUE,
    password    VARCHAR(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS tempat (
    id_tempat          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pemilik         BIGINT NOT NULL REFERENCES pemilik_tempat (id_pemilik),
    nama_tempat        VARCHAR(150) NOT NULL,
    jenis_tempat       VARCHAR(50)  NOT NULL,
    status_verifikasi  VARCHAR(30)  NOT NULL DEFAULT 'PENDING',
    status_tempat      VARCHAR(30)  NOT NULL DEFAULT 'AVAILABLE',
    harga_sewa         NUMERIC(15,2) NOT NULL CHECK (harga_sewa >= 0),
    lokasi             TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS fasilitas (
    id_fasilitas    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama_fasilitas  VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS tempat_fasilitas (
    id_tempat     BIGINT NOT NULL REFERENCES tempat (id_tempat) ON DELETE CASCADE,
    id_fasilitas  BIGINT NOT NULL REFERENCES fasilitas (id_fasilitas) ON DELETE CASCADE,
    PRIMARY KEY (id_tempat, id_fasilitas)
);

CREATE TABLE IF NOT EXISTS foto_tempat (
    id_foto    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_tempat  BIGINT NOT NULL REFERENCES tempat (id_tempat) ON DELETE CASCADE,
    url_foto   VARCHAR(500) NOT NULL
);

CREATE TABLE IF NOT EXISTS booking (
    id_booking       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_tempat        BIGINT NOT NULL REFERENCES tempat (id_tempat) ON DELETE CASCADE,
    id_penyewa       BIGINT NOT NULL REFERENCES penyewa (id_penyewa),
    tanggal_mulai    DATE NOT NULL,
    tanggal_selesai  DATE NOT NULL,
    status_booking   VARCHAR(30) NOT NULL DEFAULT 'PENDING',
    CONSTRAINT chk_booking_tanggal CHECK (tanggal_selesai > tanggal_mulai)
);

CREATE TABLE IF NOT EXISTS ulasan (
    id_ulasan   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_penyewa  BIGINT NOT NULL REFERENCES penyewa (id_penyewa),
    id_tempat   BIGINT NOT NULL REFERENCES tempat (id_tempat) ON DELETE CASCADE,
    rating      INT NOT NULL CHECK (rating BETWEEN 1 AND 5),
    komentar    TEXT
);

CREATE INDEX IF NOT EXISTS idx_tempat_pemilik    ON tempat (id_pemilik);
CREATE INDEX IF NOT EXISTS idx_tempat_status     ON tempat (status_verifikasi, status_tempat);
CREATE INDEX IF NOT EXISTS idx_foto_tempat       ON foto_tempat (id_tempat);
CREATE INDEX IF NOT EXISTS idx_booking_tempat    ON booking (id_tempat, status_booking);
CREATE INDEX IF NOT EXISTS idx_booking_penyewa   ON booking (id_penyewa);
CREATE INDEX IF NOT EXISTS idx_ulasan_tempat     ON ulasan (id_tempat);

